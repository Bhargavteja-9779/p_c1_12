"""plan_v2 summary (experiments/plan_v2.md): Holm over {H7a, H7b} x {PreDist M1, CARE} seed-0 p-values (alpha 0.05),
H7c/H7d per dataset, robustness = number of seeds (of those available, target 5) with unadjusted p < 0.05.
Written 2026-11-24 after the PreDist seed-0 analysis and BEFORE any CARE plan_v2 output existed (procedure fixed by
plan_v2.md; this script only implements it). Usage: plan_v2_summary.py  -> results/plan_v2/summary.{json,md}"""
import json, os, glob

ROOT = os.environ.get("PLANV2_ROOT", "results")
DS = ["predist1", "care"]
ALPHA = 0.05


def load(ds, seed):
    p = f"{ROOT}/plan_v2/{ds}/seed{seed}/summary.json"
    return json.load(open(p)) if os.path.exists(p) else None


def holm(pvals):
    """pvals: dict name -> p. Returns dict name -> (rejected, threshold used). Step-down, stop at first failure."""
    order = sorted(pvals, key=lambda k: pvals[k]); m = len(order); out = {}; stop = False
    for i, k in enumerate(order):
        thr = ALPHA / (m - i)
        rej = (not stop) and pvals[k] < thr
        stop = stop or not rej
        out[k] = (rej, thr)
    return out


s0 = {d: load(d, 0) for d in DS}
missing = [d for d in DS if s0[d] is None]
res = {"missing_seed0": missing}
if not missing:
    p = {f"{h}_{d}": s0[d][f"{h}_p"] for d in DS for h in ("H7a", "H7b")}
    H = holm(p)
    res["holm"] = {k: {"p": p[k], "threshold": H[k][1], "rejected_H0": H[k][0]} for k in p}
for d in DS:
    if s0[d] is None: continue
    seeds = sorted(int(x.split("seed")[-1]) for x in glob.glob(f"{ROOT}/plan_v2/{d}/seed*") if load(d, int(x.split("seed")[-1])))
    S = {sd: load(d, sd) for sd in seeds}
    res[d] = {
        "seed0": {k: s0[d][k] for k in ("tau_ET", "tau_EH", "tau_CT", "H7a_diff", "H7a_ci", "H7a_p", "H7b_diff", "H7b_ci",
                                        "H7b_p", "H7c_share_threshold", "H7c_share_window", "sel_ratio", "H7d_ci",
                                        "H7d_share_detectors_ratio_lt1", "H7d_supported")},
        "seeds_available": seeds,
        "robust_H7a_n": sum(S[x]["H7a_p"] < ALPHA for x in seeds),
        "robust_H7b_n": sum(S[x]["H7b_p"] < ALPHA for x in seeds),
        "robust_H7d_n": sum(bool(S[x]["H7d_supported"]) for x in seeds),
    }
os.makedirs(f"{ROOT}/plan_v2", exist_ok=True)
json.dump(res, open(f"{ROOT}/plan_v2/summary.json", "w"), indent=1, default=float)
L = ["# plan_v2 summary (generated by scripts/plan_v2_summary.py)", ""]
if missing: L.append(f"Seed-0 missing for: {missing} -> Holm not computed.")
else:
    L += ["| test | p (one-sided) | Holm threshold | H0 rejected |", "|---|---|---|---|"]
    L += [f"| {k} | {v['p']:.4f} | {v['threshold']:.4f} | {v['rejected_H0']} |" for k, v in res["holm"].items()]
for d in DS:
    if d not in res: continue
    r = res[d]; n = len(r["seeds_available"])
    L += ["", f"## {d}", f"seed 0: tau ET {r['seed0']['tau_ET']:.3f}, EH {r['seed0']['tau_EH']:.3f}, CT {r['seed0']['tau_CT']:.3f};"
          f" H7c shares {r['seed0']['H7c_share_threshold']:.3f} / {r['seed0']['H7c_share_window']:.3f};"
          f" H7d ratio {r['seed0']['sel_ratio']:.3f} CI {[round(x, 3) for x in r['seed0']['H7d_ci']]} supported={r['seed0']['H7d_supported']}",
          f"robustness (seeds {r['seed0'] and r['seeds_available']}): H7a {r['robust_H7a_n']}/{n}, H7b {r['robust_H7b_n']}/{n},"
          f" H7d {r['robust_H7d_n']}/{n} (claim robust only if >= 4 of 5 seeds)"]
open(f"{ROOT}/plan_v2/summary.md", "w").write("\n".join(L) + "\n")
print("\n".join(L))
