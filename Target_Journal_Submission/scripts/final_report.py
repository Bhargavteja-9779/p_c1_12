#!/usr/bin/env python3
"""Section 12 report, generated from result files only (no LLM). Safe to re-run.
Writes results/metrics.json, results/statistics.json, tables/*.csv|md, results/RESULTS_SUMMARY.md, figures/*.png"""
import glob, json, os
import numpy as np, pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(ROOT, "code", "results")
OUTR, OUTT, OUTF = (os.path.join(ROOT, d) for d in ("results", "tables", "figures"))
for d in (OUTR, OUTT, OUTF):
    os.makedirs(d, exist_ok=True)
rd = lambda p: pd.read_csv(os.path.join(R, p)) if os.path.exists(os.path.join(R, p)) else None
metrics, stats, lines = {}, {}, []


def md(df, name, title):
    df.to_csv(os.path.join(OUTT, name + ".csv"), index=False)
    s = df.round(3).to_markdown(index=False) if hasattr(df, "to_markdown") else df.round(3).to_string(index=False)
    open(os.path.join(OUTT, name + ".md"), "w").write(f"# {title}\n\n{s}\n")
    lines.extend([f"### {title}", "", s, ""])


lines += ["# RESULTS SUMMARY (auto-generated by scripts/final_report.py from result files only)", ""]
# ---- PreDist protocol gap (M1 development, M2 post hoc)
for m in (1, 2):
    g = rd(f"protocol_gap/m{m}_gap.csv"); ci = rd(f"protocol_gap/m{m}_ci.csv")
    if g is None:
        continue
    cols = ["method", "ev_f05", "ev_precision", "cont_alarm_precision", "precision_ratio", "cont_fa_per_sub_year", "cont_recall_at_B2"]
    t = g[cols].copy()
    if ci is not None:
        t = t.merge(ci[["method", "infl_same_lo", "infl_same_hi", "cont_fa_same_lo", "cont_fa_same_hi"]], on="method", how="left")
    md(t, f"predist_m{m}_protocol_gap", f"PreDist manufacturer {m}: event protocol vs continuous protocol"
       + (" (M2: post hoc, test set burned)" if m == 2 else " (development data)"))
    metrics[f"predist_m{m}_precision_ratio"] = {"min": float(g.precision_ratio.min()), "max": float(g.precision_ratio.replace(np.inf, np.nan).max())}
    rk = os.path.join(R, f"protocol_gap/m{m}_rank.json")
    if os.path.exists(rk):
        stats[f"predist_m{m}_rank"] = json.load(open(rk))
# ---- CARE (Round 6)
care = sorted(glob.glob(os.path.join(R, "round6", "seed*", "protocol_compare_care.csv")))
allc = []
for p in care:
    d = pd.read_csv(p); d["seed_tag"] = os.path.basename(os.path.dirname(p)).replace("seed", ""); allc.append(d)
    stats[f"care_{d.seed_tag.iloc[0]}"] = json.load(open(os.path.join(os.path.dirname(p), "summary.json")))
if allc:
    C = pd.concat(allc)
    s0 = C[C.seed_tag == "0"]
    if len(s0):
        md(s0[["method", "E_best_f05", "E_best_prec", "lofo_rec_B2", "lofo_fa_B2", "lofo_prec_B2", "prec_inflation",
               "infl_ci_lo", "infl_ci_hi", "infl_p_holm", "cont_fa_at_Ebest", "sel_rate_ratio", "sel_rr_ci_lo", "sel_rr_ci_hi"]],
           "care_seed0", "CARE wind SCADA, pre-registered run (seed 0), LOFO operating points")
    conf = C[C.seed_tag.isin([str(s) for s in range(100, 105)])]
    if len(conf):
        agg = conf.groupby("method").agg(n_seeds=("seed_tag", "nunique"), infl_mean=("prec_inflation", "mean"),
                                         infl_sd=("prec_inflation", "std"), infl_ci_lo_min=("infl_ci_lo", "min"),
                                         lofo_rec_B2_mean=("lofo_rec_B2", "mean"), lofo_rec_B2_sd=("lofo_rec_B2", "std"),
                                         E_best_f05_mean=("E_best_f05", "mean")).reset_index()
        md(agg, "care_confirm_seeds", "CARE confirmation seeds 100-104 (mean, sd over seeds)")
        metrics["care_confirm"] = agg.to_dict(orient="records")
# ---- chance level, resolution
ch = rd("chance_level.csv")
if ch is not None:
    s = ch.groupby("m").above_chance_holm05.agg(["sum", "count"]).reset_index()
    md(s, "chance_level_summary", "Operating points beating random alarms at the same FA rate (Holm 0.05)")
res = rd("round5/resolution.csv")
if res is not None:
    md(res, "resolution", "Statistical resolution of the event protocol (analytic)")
# ---- multiplicity ledger
vt = os.path.join(ROOT, "state", "variants_tried.csv")
if os.path.exists(vt):
    v = pd.read_csv(vt, comment="#")
    stats["n_variants_tried"] = int(len(v))
    lines += [f"Variants/ideas tried (state/variants_tried.csv): {len(v)}", ""]
# ---- budget
b = json.load(open(os.path.join(ROOT, "state", "budget.json")))
metrics["compute"] = b
lines += ["## Compute", f"ledgered machine-hours: {sum(x.get('machine_h', 0) for x in b['cycles'].values()):.2f} "
          f"(ceiling {b['global_ceiling_h']}); prior cycles: {b.get('prior_note', '')}", ""]
json.dump(metrics, open(os.path.join(OUTR, "metrics.json"), "w"), indent=1, default=float)
json.dump(stats, open(os.path.join(OUTR, "statistics.json"), "w"), indent=1, default=float)
open(os.path.join(OUTR, "RESULTS_SUMMARY.md"), "w").write("\n".join(lines))
print("\n".join(lines[:200]))
